def build(out_dir, dim, micro, fact_wave, fact_topic, fact_headline, cross, waves):
    n = lambda p: len([f for f in os.listdir(out_dir) if f.startswith(p)])
    cnt = dim.시계열비교가능.value_counts()
    per = (dim.groupby(["대분류코드","대분류"]).size().reset_index(name="지표수"))
    cats = pd.read_csv(os.path.join(out_dir,"dim_category.csv")).merge(per, how="left",
              on=["대분류코드","대분류"]).fillna({"지표수":0})
    lines = ["| 코드 | 대분류 | 주요 응답주체 | 지표수(숨김 포함) |","|---|---|---|---|"]
    for _,r in cats.iterrows():
        lines.append(f"| {r.대분류코드} | {r.대분류} | {r['주요 응답주체']} | {int(r.지표수)} |")
    pop = {(r.응답주체, r.조사연도): r.n for _, r in
           micro.groupby(["응답주체","조사연도"])["응답자ID"].nunique().reset_index(name="n").iterrows()}
    txt = TPL.format(
        n_dim=n("dim_"), n_fact=n("fact_"), n_micro=n("micro_"),
        n_ind=len(dim), n_y=int(cnt.get("Y",0)), n_cond=int(cnt.get("조건부",0)), n_n=int(cnt.get("N",0)),
        n_cat=len(cats), n_cat_used=int(dim.loc[dim.화면표시 != "숨김", "대분류코드"].nunique()),
        n_topic=int(dim.loc[dim.화면표시 != "숨김", "소주제코드"].nunique()),
        n_micro_rows=len(micro),
        s1=pop[("학생",2021)], p1=pop[("학부모",2021)], t1=pop[("교사",2021)],
        s2=pop[("학생",2025)], p2=pop[("학부모",2025)], t2=pop[("교사",2025)],
        sc1=pop[("학교",2021)], sc2=pop[("학교",2025)],
        n_cross=len(cross), n_cross_ok=int((cross.성립여부=="성립").sum()),
        cat_table="\n".join(lines),
        n_fw=len(fact_wave), n_ft=int(fact_topic.소주제코드.nunique()), n_fh=len(fact_headline))
    p = os.path.join(out_dir, "00_전달안내.md")
    open(p, "w").write(txt)
    return p
